import { writeFileSync } from "node:fs";
import { buildUniverse } from "../dist/index.js";

const out = process.argv[2];
if (!out) throw new Error("usage: seed-sql.mjs <output.sql>");

const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const rows = buildUniverse().map(
  (i) =>
    `(${q(i.symbol)}, ${q(i.isin)}, ${q(i.name)}, ${q(i.sector)}, ${q(i.mcapBucket)}, ${q(i.assetClass)}, ${i.lotSize}, ${i.tickSize}, ${i.basePrice.toFixed(2)}, ${i.circuitPct ?? "NULL"})`,
);
const sql = `-- Generated by packages/market/scripts/seed-sql.mjs from buildUniverse(); do not edit by hand.
INSERT INTO instruments (symbol, isin, name, sector, mcap_bucket, asset_class, lot_size, tick_size, prev_close, circuit_pct) VALUES
${rows.join(",\n")};
`;
writeFileSync(out, sql);
console.log(`wrote ${rows.length} instruments to ${out}`);
